## ১. জাবেদা কী? (Concept of Journal)
ব্যবসায়ের কোনো আর্থিক ঘটনা ঘটার সাথে সাথে তারিখের ক্রমানুসারে ডেবিট ও ক্রেডিট পক্ষ বিশ্লেষণ করে সংক্ষিপ্ত ব্যাখ্যাসহ সর্বপ্রথম যে বইতে লেখা হয়, তাকে **জাবেদা (Journal)** বলে।
- **উৎপত্তি:** ফরাসি শব্দ **'Jour'** (জার) থেকে Journal শব্দটির উৎপত্তি, যার অর্থ হলো **'দিন (Day)'**।
- **উপাধি:** জাবেদাকে বলা হয় হিসাবের **'প্রাথমিক বই'** বা **'দৈনিক বই (Book of Original Entry)'**।

