## ২. ব্যালেন্সিং বা জের নির্ণয় (Balancing)
হিসাবের ডেবিট ও ক্রেডিট পাশের যোগফলের পার্থক্য বা ব্যবধান নির্ণয় করার নামই **জের টানা বা ব্যালেন্সিং (Balancing)**।

### গুরুত্বপূর্ণ সংকেতের পূর্ণরূপ ও অর্থ:
- **c/d (Carried Down):** নিচে নীত বা স্থানান্তর করা হলো (চলতি মাসের শেষ তারিখে ঘাটতি দিকে বসে)।
- **b/d (Brought Down):** উপর থেকে আনীত (পরবর্তী মাসের ১ তারিখে বিপরীত দিকে বসে)।
- **c/f (Carried Forward):** সম্মুখে নীত (পৃষ্ঠার শেষে স্থানান্তরের সময়)।
- **b/f (Brought Forward):** পেছন থেকে আনীত (নতুন পৃষ্ঠার শুরুতে)।

