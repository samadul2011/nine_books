## ২. সহকারী খতিয়ান (Subsidiary Ledger)
প্রতিটি দেনাদার ও পাওনাদারের নামে পৃথক পৃথক যে খতিয়ান খোলা হয়, তাকে **সহকারী খতিয়ান** বলে।
- উদাহরণ: মি. রহিম হিসাব, মেসার্স করিম ব্রাদার্স হিসাব, যমুনা ট্রেডার্স হিসাব।
- **উদ্দেশ্য:** নির্দিষ্ট গ্রাহক বা সরবরাহকারীর কাছে কত পাওনা বা দেনা রয়েছে তা তাৎক্ষণিকভাবে জানা।

