## ১. সাধারণ খতিয়ান (General Ledger)
ব্যবসায়ের যাবতীয় প্রধান হিসাব খাতসমূহ (যেমন: নগদান হিসাব, ক্রয় হিসাব, বিক্রয় হিসাব, বেতন হিসাব, দেনাদার নিয়ন্ত্রণ হিসাব, পাওনাদার নিয়ন্ত্রণ হিসাব) যে বইতে রাখা হয়, তাকে সাধারণ খতিয়ান বলে।
