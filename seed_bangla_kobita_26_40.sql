## 📖 মূল পাঠ (কবিতা)

বন্দনা
শাহ মুহম্মদ সগীর



দ্বিতীয়ে প্রণাম করৌ মাও বাপ পাএ।
যান দয়া হত্তে জন্ম হৈল বসুধায় ॥
পিপিড়ার ভয়ে মাও না থুইলা মাটিত।
কোল দিআ বুক দিআ জগতে বিদিত ॥
তান দয়া হন্তে হেল এ ধড় বিশাল ॥
না খাই খাওয়াএ পিতা না পরি পরাএ।
কত দুক্ষে একে একে বছর গোঞ্াএ ॥
পিতাক নেহায় জিউ জীবন যৌবন।
কনে বা সুধিব তান ধারক কাহন ॥
ওস্তাদে প্রণাম করো খিতা হস্তে বাড়।
দোসর-জনম দিলা তিহ সে আন্গার ॥
আন্মা পুরবাসী আছ জথ পৌরজন।
ইষ্ট মিত্র আদি জথ সভাসদগণ ॥
তান সভান পদে মোহার বহুল ভকতি।
সপুটে প্রণাম মোহার মনোরথ গতি
মুহম্মদ সগীর হীন বহৌ পাপ ভার ।
সভানক পদে দোয়া মাগো বার বার ॥

