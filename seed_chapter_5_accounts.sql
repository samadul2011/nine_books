■ ১. আধুনিক বা সমীকরণভিত্তিক শ্রেণিবিভাগ (Modern Approach):
━━━━━━━━━━━━━━━━━━━━━━━━━━━━
হিসাব সমীকরণ: **A = L + E** (Assets = Liabilities + Equity)
যেখানে মালিকানাস্বত্ব (E) = মূলধন (C) + আয় (R) - ব্যয় (E) - উত্তোলন (D)।

এই সমীকরণের ওপর ভিত্তি করে হিসাবকে প্রধানত **৫টি শ্রেণিতে** বিভক্ত করা হয়:

### ১. সম্পদ হিসাব (Assets):
কারবারের নিজস্ব মালিকানাধীন এমন বস্তুগত বা অবস্তুগত বিষয় যা ভবিষ্যতে অর্থনৈতিক সুবিধা ও নগদ অর্থ অর্জনে সাহায্য করে।
• চলতি সম্পদ: হাতে নগদ, ব্যাংক জমা, প্রাপ্য হিসাব (দেনাদার), সমাপনী মজুদ পণ্য, অগ্রিম খরচ, প্রাপ্য কমিশন/সুদ।
• স্থায়ী সম্পদ: আসবাবপত্র, অফিস সরঞ্জাম, যন্ত্রপাতি, জমি ও দালানকোঠা, মোটরগাড়ি।

### ২. দায় হিসাব (Liabilities):
কারবারের সম্পদের ওপর তৃতীয় পক্ষের আর্থিক দাবি বা পাওনাকে দায় বলে।
• চলতি দায়: প্রদেয় হিসাব (পাওনাদার), ব্যাংক জমাতিরিক্ত, স্বল্পমেয়াদি ঋণ, বকেয়া বেতন, বকেয়া ভাড়া, অনুপার্জিত বা অগ্রিম আয়।
• দীর্ঘমেয়াদি দায়: ব্যাংক ঋণ, বন্ধকী ঋণ, ঋণপত্র বা ডিবেঞ্চার।

### ৩. মালিকানাস্বত্ব হিসাব (Owner's Equity):
কারবারের মোট সম্পদের ওপর মালিকের যে নিট অধিকার বা দাবি থাকে, তাকে মালিকানাস্বত্ব বলে।
• মূলধন হিসাব (Capital) - মালিকের বিনিয়োগ যা স্বত্ব বাড়ায়।
• সাধারণ সঞ্চিতি (General Reserve) - মুনাফা থেকে আলাদা করে রাখা অংশ।
• উত্তোলন হিসাব (Drawings) - এটি একটি বিপরীত মালিকানাস্বত্ব হিসাব (Contra-Equity), যা মালিকানাস্বত্ব হ্রাস করে।

### ৪. আয় বা রাজস্ব হিসাব (Revenues):
পণ্য বিক্রয় বা কোনো সেবা প্রদানের বিনিময়ে কারবারে যে অর্থ বা পাওনা অর্জিত হয়।
• পণ্য বিক্রয় হিসাব, সেবা আয়, বাড়ি ভাড়া প্রাপ্তি, বিনিয়োগের সুদ, ব্যাংক জমার সুদ, প্রাপ্ত কমিশন, প্রাপ্ত বাট্টা।

### ৫. ব্যয় হিসাব (Expenses):
আয় অর্জনের উদ্দেশ্যে পণ্য তৈরি, ক্রয় বা দৈনন্দিন কারবার পরিচালনায় যেসব সেবা গ্রহণ বা আর্থিক ত্যাগ স্বীকার করা হয়।
• পণ্য ক্রয় হিসাব, কর্মচারীদের বেতন, দোকান ও অফিস ভাড়া, পরিবহন খরচ, বিদ্যুৎ ও ইউটিলিটি বিল, বিজ্ঞাপন খরচ, মনিহারি, স্থায়ী সম্পদের অবচয়।

