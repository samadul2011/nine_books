 /**
  * Flip English & Bengali in title so English comes 1st and Bengali Meaning comes latter.
  * E.g. '৫ম অধ্যায়: চারপাশের সমস্যা (Unit 5: Problems Around Us)'
  * -> 'Unit 5: Problems Around Us (৫ম অধ্যায়: চারপাশের সমস্যা)'
  */
 export function flipEnglishBengaliTitle(text) {
   if (!text) return text
   const match = text.match(/^([^(]+?)\s*\(([^)]+)\)\s*$/)
   if (match) {
     const banglaPart = match[1].trim()
     const englishPart = match[2].trim()
     if (/[a-zA-Z]/.test(englishPart) && /[\u0980-\u09FF]/.test(banglaPart)) {
       return `${englishPart} (${banglaPart})`
     }
   }
   return text
 }
 
 /**
  * Extract separated English and Bengali parts for custom two-line or badge rendering
  */
 export function extractEnglishAndBengaliParts(text) {
   if (!text) return { english: '', bengali: '' }
   const match = text.match(/^([^(]+?)\s*\(([^)]+)\)\s*$/)
   if (match) {
     const banglaPart = match[1].trim()
     const englishPart = match[2].trim()
     if (/[a-zA-Z]/.test(englishPart) && /[\u0980-\u09FF]/.test(banglaPart)) {
       return { english: englishPart, bengali: banglaPart }
     }
   }
   return { english: text, bengali: '' }
 }
 
 /**
  * Clean OCR, python script artifacts, typography glitches,
  * and ensure English comes 1st and Bengali comes latter in all headings.
  */
 export function cleanEnglishText(content) {
   if (!content) return ''
   let text = content
     // Keep English 1st and Bengali Meaning latter in unit headers:
     // e.g. "# ৫ম অধ্যায়: চারপাশের সমস্যা (Unit 5: Problems Around Us)"
     // -> "# Unit 5: Problems Around Us (৫ম অধ্যায়: চারপাশের সমস্যা)"
     .replace(/(^|\n)(#{1,3}\s*)([^(]+?)\s*\((Unit\s+\d+:[^)]+|Sample[^)]+)\)/gi, (match, prefix, hashes, bangla, english) => {
       return `${prefix}${hashes}${english.trim()} (${bangla.trim()})`
     })
     // Remove python artifact f"-)
     .replace(/\\c,\s*f"-\)/g, '')
     .replace(/f"-\)\s*/g, '')
     .replace(/\\c,\s*/g, '')
     // Re-join sentences split incorrectly around f"-)
     .replace(/this is how to throw\s*back a fish/g, 'this is how to throw back a fish')
     .replace(/inspiration throughout his\s*career/g, 'inspiration throughout his career')
     .replace(/bioenergy\s*\.\s*f"-\)/g, 'bioenergy.')
     .replace(/membership site\s*\.\s*f"-\)/g, 'membership site.')
     // Fix typo in benna/henna
     .replace(/I don 't sing henna on Sundays/g, "I don't sing benna on Sundays")
     .replace(/sing henna on Sundays/g, 'sing benna on Sundays')
     // Fix typography
     .replace(/don 't/g, "don't")
     .replace(/won 't/g, "won't")
     .replace(/can 't/g, "can't")
     .replace(/tum someone else's stomach/g, "turn someone else's stomach")
     .replace(/sweep a comer/g, "sweep a corner")
 
   return text
 }

