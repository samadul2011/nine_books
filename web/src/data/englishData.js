/**
 * Automatically detects any remaining exercise questions in English units
 * and provides clear, pedagogical answers if not already provided.
 */
function autoGenerateMissingAnswers(text) {
  const lines = text.split('\n')
  const newLines = []
  let inQuestionSection = false

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    const trimmed = line.trim()

    // Check if section header indicates questions
    if (/^###\s*❓?\s*(?:Answer the following questions|Questions?:?|Now answer the questions)/i.test(trimmed)) {
      inQuestionSection = true
      newLines.push(line)
      continue
    }

    if (inQuestionSection && (trimmed.startsWith('## ') || trimmed.startsWith('# ') || trimmed === '---')) {
      inQuestionSection = false
      newLines.push(line)
      continue
    }

    // In a question section, if line is a question without answer block
    if (
      inQuestionSection &&
      trimmed.length > 15 &&
      trimmed.endsWith('?') &&
      !trimmed.startsWith('>') &&
      !trimmed.startsWith('**Q')
    ) {
      // Check if next line is already an answer
      const next1 = lines[i + 1]?.trim() || ''
      const next2 = lines[i + 2]?.trim() || ''
      if (!next1.startsWith('> 💡') && !next1.startsWith('**Answer') && !next2.startsWith('> 💡') && !next2.startsWith('**Answer')) {
        const cleanQ = trimmed.replace(/^[0-9ivx]+\.\s*/i, '')
        const inferredAnswer = generateContextualAnswer(cleanQ)
        newLines.push(`> ❓ **Q: ${cleanQ}**`)
        newLines.push(`> 💡 **Answer:** ${inferredAnswer}`)
        newLines.push('')
        continue
      }
    }

    newLines.push(line)
  }

  return newLines.join('\n')
}

