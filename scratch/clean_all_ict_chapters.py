def clean_page(p_num):
    raw = raw_pages.get(f'page_{p_num}', '')
    lines = raw.split('\n')
    cleaned = []
    
    # Check if page is opening page of a chapter (pages 6, 20, 47, 69, 115)
    is_opening = p_num in [6, 20, 47, 69, 115]
    
    # Filter out standalone chapter headers appearing in middle of pages
    chapter_header_pat = re.compile(r'^(তথ্য ও যোগাযোগ প্রযুক্তি ও আমাদের বাংলাদেশ|কম্পিউটার রক্ষণাবেক্ষণ ও সাইবার নিরাপত্তা|ইন্টারনেট ও ওয়েব পরিচিতি|আমার লেখালেখি ও হিসাব|মাল্টিমিডিয়া ও গ্রাফিক্স|প্রোগ্রামিংয়ের মাধ্যমে সমস্যার সমাধান)\s*(\d+|[০-৯]+)?$')
    
    for l in lines:
        s = l.strip()
        if not s:
            continue
            
        if chapter_header_pat.match(s):
            continue
            
        # Check drop patterns
        should_drop = False
        for reg in DROP_LINE_REGEXES:
            if reg.search(s):
                should_drop = True
                break
        if should_drop:
            continue
            
        # On opening page, discard everything before/around learning outcomes that is not a bullet
        if is_opening:
            if not s.startswith('>') and not s.endswith('পারব;') and not s.endswith('পারবঃ') and not s.endswith('পারব।'):
                continue
            
        # Apply typo corrections
        for pat, rep in TYPO_MAP:
            s = re.sub(pat, rep, s)
            
        cleaned.append(s)
        
    page_text = '\n'.join(cleaned)
    return page_text

def build_chapter(start_p, end_p):
    parts = []
    for p in range(start_p, end_p + 1):
        txt = clean_page(p)
        if txt.strip():
            parts.append(txt.strip())
    full_txt = '\n\n'.join(parts)
    
    # Apply topic replacements
    for pat, repl in TOPIC_REPLACEMENTS:
        full_txt = pat.sub(repl, full_txt)
        
    return full_txt

